    internal static void Ensure(CareerData d)
    {
        if (d.Esports.OrganizationContentVersion >= 1) return;
        foreach (var club in d.Esports.Clubs.Where(c => c.Id != d.Esports.OwnedClub?.ClubId))
            club.Motto = ClubDescription(d, club, CareerCommerce.IdentityIndex(d, club.Id));
        d.Esports.OrganizationContentVersion = 1;
    }
    internal static string ClubName(CareerData d, string country, string id)
    {
        var bank = Clubs[HumanNames.Region(country)]; int start = CareerEngine.StableHash(d.WorldId + ":club-name:" + id) % bank.Length;
        for (int n = 0; n < bank.Length; n++)
        { string candidate = bank[(start + n) % bank.Length]; if (d.Esports.Clubs.All(c => c.Name != candidate)) return candidate; }
        return bank[start] + "二队";
    }
    internal static string ClubDescription(CareerData d, CareerClub club, int kind)
    {
        int seed = CareerEngine.StableHash(d.WorldId + ":club-description:" + club.Id);
        return ClubBackgrounds[HumanNames.Region(club.Country)][seed % 8] + Ambitions[kind][seed / 8 % 8];
    }
