    public static string TemplateId(AiOptions options) => AvailableTemplates(options).Any(t => t.Id == options.PromptTemplate) ? options.PromptTemplate : DefaultTemplate;
    public static PromptTemplate Template(AiOptions options) => AvailableTemplates(options).First(t => t.Id == TemplateId(options));
    public static string Default(AiOptions options, string id)
    {
        string template = TemplateId(options);
        if (options.CustomPromptTemplates?.TryGetValue(template, out var custom) == true)
        {
            if (custom.Sections.TryGetValue(id, out var text)) return text;
            template = custom.BaseTemplate;
        }
        // 独立预设只覆盖其提供的模块；旧模板和玩家已保存的修改继续使用原有内容。
        var preset = template switch { "reduced-aggression" => ReducedAggression.Value, "tieba-aggressive" => TiebaAggressive.Value, _ => null };
        if (preset?.TryGetValue(id, out var presetText) == true) return presetText;
        return (template == "legacy" ? LegacySections : Sections).First(s => s.Id == id).DefaultText;
    }
    public static void SelectTemplate(AiOptions options, string id)
    {
        if (!AvailableTemplates(options).Any(t => t.Id == id)) throw new ArgumentException("未知提示词模板。");
        string previous = TemplateId(options);
        if (previous == id) return;
        options.PromptTemplateOverrides ??= new();
        options.PromptTemplateOverrides[previous] = new(options.PromptOverrides ?? new());
        options.PromptOverrides = options.PromptTemplateOverrides.TryGetValue(id, out var saved) ? new(saved) : new();
        options.PromptTemplateOverrides.Remove(id);
        options.PromptTemplate = id;
    }
