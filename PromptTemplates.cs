游戏知识：
铁甲战士（战士）：
初始：80血，初始遗物燃烧之血，战斗后回血。
核心机制：消耗卡牌换取收益、易伤和力量增益攻击、以自伤换强力效果。消耗卡牌是需要谨慎抉择的行为，一般能不消耗就不消耗。自伤被认为代价过高收益过低，如果本来就打得过，那自伤白扣血；打不过的，自伤死得更快。
力量流：通过想尽办法开出恶魔形态叠力量，飞剑回旋镖和旋风斩等多段攻击吃力量加成极高。是主要流派。
防战流：叠格挡后用全身撞击将格挡值转化为伤害，早期拿到壁垒和全身撞击时可以考虑。然而经常有格挡没有全身撞击，摸到全身撞击又没有防牌，设计师左右脑互搏之作。
注意，因为担心消耗到最后没牌可打，只有大卡组会玩消耗流。防战被认为是背离设计思路的打法。

静默猎手（猎人）：
初始：70血，初始遗物蛇之戒指，每场战斗开始额外抽2张牌。初始牌组比别人多一张打击和一张防御，是最强初始牌组。
核心机制：“运转”——大量过牌和弃牌快速过滤牌库，找到关键组件形成循环，奇巧牌因为被丢弃后可以免费打出，见到就抓准没错。
毒流核心：腐蚀波，非常强力。
腐蚀波：打出后，本回合每抽一张牌就给所有敌人上2层毒（升级后3层）。
触媒：新加入的牌，能力卡，中毒额外触发一次，但是因为结算多，层数掉得快很容易断。
毒雾：1费每回合开始群体叠2层（升级后额外多1层），非常慢，一般没人用，万不得已才会抓。

故障机器人：
核心机制：充能球+集中。
四种球：
闪电球：回合结束随机打1敌3，激发时8伤。
冰霜球：回合结束给2格挡，激发时5格挡。
黑暗球：回合结束自增伤害6，激发时打出。
等离子球：回合开始+1能量，激发时回2能量。
规则：球栏满后再产球，最右侧的球被激发。集中越高，球效果越强。激发是对于充能球超出上限的惩罚。需要尽量避免。
集中：每点集中让所有球的被动和触发效果+1（等离子球除外）。
碎片整理：获得1点集中（升级后2点），金色能力。
偏差认知：获得4点集中（升级后5点），每回合开始失去1点，负面效果太大一般不考虑抓取。
主要流派：电球流（堆集中+大量闪电球）、冰球防御流（堆集中+无限冰球，全程高防）、黑球核弹流（保留黑球无限叠伤）。没啥人会蠢到用故障机器叠力量敏捷玩物理机。主流观点认为给自己塞状态牌的流派相当卡手，纯惩罚自己，无法实现，不知道这玩意设计出来干啥。

亡灵契约师：
初始：66血，初始遗物缚魂命匣，每回合开始给奥斯提回复1点生命。
奥斯提：骨手。拥有独立生命值，可独立于本体攻击敌人，不受到针对本体的负面效果影响，会优先承受针对本体的攻击伤害。
主要流派灾厄相关机制：
给敌人叠加灾厄值。敌人回合结束时，如果灾厄值大于或等于其生命值，直接死亡（无视护盾）。
与中毒的区别：中毒在敌人回合开始前结算并造成伤害，灾厄在敌人回合结束后结算，且不造成伤害而是直接处决。一般情况下灾厄数值高且不会减少，是好于同数值的中毒的。
灾厄不会随时间衰减。
例子牌：荒疫打击（造成8点伤害，施加等于未被格挡伤害值的灾厄）、精神过载（获得3费抽2张，回合开始对自己施加3点灾厄）（给自己加灾厄负面效果太高，一般被认为无法接受）。
灵魂流是杀戮尖塔2最强运转，无论何时看到就抓一点问题没有。

储君：
核心机制：辉星与铸剑。还有花活无色牌流派，这玩意极其不稳定，没人玩。
辉星：储君专属资源。部分卡牌同时消耗能量和辉星。辉星不够时铸剑牌容易卡手。
辉星流：核心围绕辉星的生成与消耗，通过优质牌在攻防的同时将费用转化为辉星，再利用辉星打出多段伤害和强力buff完成速杀。通过辉光/崇拜/隐秘藏品/胜券在王囤积高额辉星，辐射/星尘/月面射击充当输出终端。
铸剑流：使用铸剑牌铸出大剑，超过敌人生命时打出，只打出一次，一击结束战斗，非常酷炫帅气。
核心牌：铸剑者、追踪之刃、熔炉、招架。
打法：只要能铸的都是key卡，两个熔炉就能铸出巨剑。

游戏玩法：
杀戮尖塔2前期极度高压，低楼层暴毙都是常事。必须见牌就抓才能提升战力，避战精英才能减少战损，精英被设计出来就是不鼓励玩家挑战的障碍。
大卡组是构筑目标。不要跳过卡牌，删牌是惩罚选项，对卡组负提升。卡组越小越容易被塞负面牌，尤其在三层，必须尽早增大卡组。
药水可以沿途补充，获取药水也是爬塔本事，如何使用药水则是技巧，通关后还有剩余则显得相对游刃有余。
一般而言防御牌大于攻击牌。

关卡与敌人：
常规流程共三幕。第一幕是密林或暗港，第二幕是巢穴，第三幕是荣耀，击败第三幕BOSS后通关。进阶10的第三幕需要连续击败两个BOSS。

第一幕：密林
藤蔓、树木和菌类覆盖着尖塔遗迹，石墙与建筑之间长满植被。敌人包括植物、菌类生物、异鸟与寄生生物。
精英：
旧日雕像：前两回合处于沉睡与苏醒阶段，第1回合睡眠，第2回合苏醒并获得10点力量，第3回合开始每回合重击。拥有缓慢，玩家本回合每打出一张牌，雕像本回合受到的攻击伤害增加10%。
多尼斯异鸟：单次扑击与三连啄击交替进行，每个敌方回合结束增加1点力量，战斗拖得越久，三连击越危险。
异蛙寄生虫：第1回合向弃牌堆加入3张感染，第2回合四连击，随后交替重复。感染留在手中会在回合结束时造成伤害。死亡后出现4个扭动虫，新出现的扭动虫先眩晕一回合。
BOSS：
墨影幻灵：开战拥有8层滑溜，进阶8起为9层。每层将一次生命损失压到1点，受到多次伤害可以逐层消耗。行动按单次攻击、两连击、重击并向弃牌堆加入3张伤口、增加2点力量循环。
仪式兽：第1回合准备冲撞，之后连续冲撞，每次增加2点力量。单人战斗中，生命降至150时中断冲撞，进阶9起阈值为160；随后清除力量并眩晕一回合。第二阶段按吼叫、践踏、重击循环，吼叫使玩家下一回合只能打出1张牌，重击后继续增加力量。
同族小队：1名同族神官带着2名同族信徒共同出现。神官依次进行附带脆弱的攻击、附带虚弱的攻击、三连击和增加力量。两名信徒错开行动，轮流进行单次攻击、两连击和增加力量。

第一幕：暗港
尖塔旧时的港口与供水区域，年久失修的码头、水道和建筑连成迷宫，污浊海水中栖息着各种异变水生生物。敌人以鳗鱼、珊瑚、甲壳类和其他海洋生物为主。
精英：
花园幽灵鳗：4个一组出现，各自错开进行单次攻击、三连击和增加力量。每只幽灵鳗在一回合内首次受到攻击牌造成的生命伤害后获得格挡，单人基础值为6点，进阶8起为7点。
鬼祟珊瑚群：拥有硬化外壳，单人战斗每回合最多损失20点生命。行动按两次单次攻击、攻击并增加力量、两连击循环，需要经过多个回合才能击败。
骇鳗：单次攻击与三连击交替，三连击后获得6点活力，强化下一次攻击。生命首次降至一半时眩晕一回合，随后尖啸，施加99层易伤，再恢复攻击。
BOSS：
瀑布巨兽：开战积累蒸汽，之后在攻击、回复生命、蓄压与蒸汽炮之间循环，持续提高蒸汽数值。生命耗尽后进入爆炸准备，玩家还有一回合准备格挡，随后按累计蒸汽造成伤害。
灵魂异鱼：五回合一轮。第1回合分别向抽牌堆和弃牌堆加入1张呼唤，第2回合攻击，第3回合攻击并再加入1张呼唤，第4回合获得2层无实体，第5回合攻击并施加3层易伤。呼唤留在手中会在回合结束时失去生命，无实体期间受到的每次伤害降至1。
乐加维林族母：开战休眠3回合并拥有12点多层护甲，受到生命伤害时提前苏醒。苏醒后按单次攻击、两连击、攻击并获得格挡、吸取属性循环。每次吸取使玩家失去2点力量和2点敏捷，同时给自己增加2点力量。

第二幕：巢穴
巨大的虫巢深入尖塔内部，洞穴墙壁遍布孔洞、巢室与通道。昆虫、寄生虫和受感染的生物成群栖息，战斗中经常出现连续攻击、状态牌与持续恶化的负面效果。
精英：
残杀千足虫：由前、中、后三节组成，三节分别行动，错开进行两连击、攻击并增加力量、攻击并施加虚弱。某一节死亡时，只要还有其他部分存活，经过2回合就会复活，单人复活生命为25。需要在复活前让三节全部倒下。
蜂群术士：按蜂群连击、单次攻击、强化循环。蜂群基础为七连击，进阶9起为八连击，每次命中都向抽牌堆加入晕眩。蜂房强化后，每次命中加入的晕眩从1张逐渐增加到3张，同时力量也会提高。
感染棱柱：使技能牌附带污染，打出这些技能会积累污染层数，每层使本轮受到的每次攻击伤害增加1，敌方回合结束清除。行动中包含三连击，每4回合进一步提高技能牌施加的污染数量。
BOSS：
帝皇蟹：左右两个部位分别行动，将玩家夹在中间。玩家使用指定目标的卡牌或药水会改变朝向，背后受到的攻击伤害增加50%。左侧负责攻击、虚弱和脆弱，右侧会蓄力发射重型激光，之后休息一回合。击败一侧后，另一侧立即获得5点力量和99点格挡。
知识恶魔：第1、5、9回合分别提出一次二选一诅咒，让玩家在每回合受伤与减少抽牌、限制出牌、减少能量等代价之间选择。其余回合穿插单次攻击、三连击，以及攻击后回复生命并增加力量，拖延会同时加重输出和诅咒压力。
无厌沙虫：第1回合施加4层流沙，并加入6张狂乱逃离，其中3张进入抽牌堆，3张进入弃牌堆。流沙在每个敌方回合开始减少1层，归零时直接吞噬玩家。狂乱逃离初始消耗1点能量，每次打出增加1层流沙，同时这张牌本场战斗的费用增加1。沙虫还会交替进行连击、重咬和增加力量。

第三幕：荣耀
尖塔上层的宏伟石制建筑群，破损的高墙、拱门、柱廊与高台之间散布着昔日文明的遗迹。这里有骑士、机械构装体、活化卷轴和灵魂造物，是常规爬塔的最后一幕。
精英：
骑士团伙：连枷骑士、幽灵骑士和魔法骑士三人共同出现。连枷骑士进行单次攻击、两连击并增加力量；幽灵骑士使玩家卡牌带有虚无，回合结束时留在手中的相关卡牌会消耗；魔法骑士使卡牌降级。击败对应骑士后，其持续施加的效果解除。
机甲骑士：开战拥有3层人工制品。第1回合冲锋攻击，之后按向手牌加入4张灼伤、获得15点格挡与5点力量、重击循环。灼伤会直接影响眼前这个回合，连续强化后的重击伤害很高。
