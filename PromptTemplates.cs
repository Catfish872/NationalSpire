    private static Dictionary<string, string> ReadPreset(string id)
    {
        using var stream = typeof(PromptLibrary).Assembly.GetManifestResourceStream($"NationalSpire.PromptPresets.{id}.json")
            ?? throw new InvalidOperationException("内置提示词资源缺失：" + id);
        var sections = System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(stream)
            ?? throw new InvalidOperationException("内置提示词资源为空：" + id);
        if (sections.Any(p => !Sections.Any(s => s.Id == p.Key) || string.IsNullOrWhiteSpace(p.Value)))
            throw new InvalidOperationException("内置提示词模块无效：" + id);
        return sections;
    }
